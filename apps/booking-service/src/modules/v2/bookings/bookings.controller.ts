import { Body, Controller, Get, Param, Patch, Post, Query, UseGuards } from "@nestjs/common";
import { BookingsService } from "../../v1/bookings/bookings.service";
import {
  EmailVerifiedGuard,
  GatewayAuthGuard,
  CurrentUser,
  type AuthenticatedUser,
  ZodValidationPipe,
} from "@app/common";
import {
  type CreateBookingDto,
  createBookingSchema,
} from "../../v1/bookings/schemas/create-booking.schema";
import {
  ApiBearerAuth,
  ApiBody,
  ApiHeader,
  ApiOperation,
  ApiParam,
  ApiResponse,
  ApiTags,
} from "@nestjs/swagger";
import { CreateBooking } from "../../v1/bookings/schemas/swagger/create-booking";
import { type V2BookingQueryDto, v2BookingQuerySchema } from "./schemas/booking-query.schema";
import { type V2BookingResponseDto } from "./schemas/booking-response.schema";
import { type V2PaginatedBookingResponseDto } from "./schemas/paginated-booking-response.schema";
import {
  type V2UpdateBookingStatusDto,
  v2UpdateBookingStatusSchema,
} from "./schemas/update-booking.schema";
import { IdempotencyKey } from "./decorators/idempotency-key.decorator";
import { V2BookingResponse } from "./schemas/swagger/booking-response";
import { V2PaginatedBookingResponse } from "./schemas/swagger/paginated-booking-response";
import { V2UpdateBooking } from "./schemas/swagger/update-booking";

@ApiTags("Bookings")
@ApiBearerAuth()
@Controller({ path: "bookings", version: "2" })
@UseGuards(GatewayAuthGuard)
export class BookingsController {
  constructor(private readonly bookingsService: BookingsService) {}

  @Get()
  @ApiOperation({
    summary: "Get current user's bookings",
    description:
      "Returns a paginated list of bookings. Users see their own bookings, Agents see bookings of their offers, Admins see all bookings.",
  })
  @ApiResponse({
    status: 200,
    description: "List of bookings retrieved successfully",
    type: V2PaginatedBookingResponse,
  })
  @ApiResponse({
    status: 400,
    description: "Invalid query parameters",
  })
  @ApiResponse({
    status: 401,
    description: "Unauthorized - Authentication required",
  })
  @ApiResponse({
    status: 404,
    description: "User not found",
  })
  async getMyBookings(
    @Query(new ZodValidationPipe(v2BookingQuerySchema))
    query: V2BookingQueryDto,
    @CurrentUser() currentUser: AuthenticatedUser,
  ): Promise<V2PaginatedBookingResponseDto> {
    return this.bookingsService.getMyBookings(
      query,
      currentUser.id,
      currentUser.role,
      true,
    ) as Promise<V2PaginatedBookingResponseDto>;
  }

  @Get(":bookingId")
  @ApiOperation({
    summary: "Get a booking by ID",
    description:
      "Returns a booking. Users can access their own bookings, Agents can access bookings of their offers, Admins can access any booking.",
  })
  @ApiParam({
    name: "bookingId",
    description: "Booking UUID",
    example: "123e4567-e89b-12d3-a456-426614174000",
    format: "uuid",
  })
  @ApiResponse({
    status: 200,
    description: "Booking found",
    type: V2BookingResponse,
  })
  @ApiResponse({
    status: 401,
    description: "Unauthorized - Authentication required",
  })
  @ApiResponse({
    status: 403,
    description:
      "Forbidden - You can only access your own bookings unless you are an Admin or the offer Agent",
  })
  @ApiResponse({
    status: 404,
    description: "Booking not found",
  })
  async getById(
    @Param("bookingId") bookingId: string,
    @CurrentUser() currentUser: AuthenticatedUser,
  ): Promise<V2BookingResponseDto> {
    return this.bookingsService.getById(
      bookingId,
      currentUser.id,
      currentUser.role,
      true,
    ) as Promise<V2BookingResponseDto>;
  }

  @Post()
  @UseGuards(EmailVerifiedGuard)
  @ApiHeader({
    name: "Idempotency-Key",
    required: true,
    description: "UUID v4 generated by the client for this create request",
  })
  @ApiOperation({
    summary: "Create a new booking",
    description:
      "Creates a new booking for an offer. New bookings are created with status pending. The user's email must be verified. Requires Idempotency-Key.",
  })
  @ApiBody({ type: CreateBooking })
  @ApiResponse({
    status: 201,
    description: "Booking created successfully",
    type: V2BookingResponse,
  })
  @ApiResponse({
    status: 400,
    description:
      "Invalid input data, missing Idempotency-Key, dates outside availability, or guests count exceeds limit",
  })
  @ApiResponse({
    status: 401,
    description: "Unauthorized - Authentication required",
  })
  @ApiResponse({
    status: 403,
    description: "Forbidden - Email is not verified",
  })
  @ApiResponse({
    status: 404,
    description: "Offer not found or not active",
  })
  @ApiResponse({
    status: 409,
    description:
      "No available slots, or Idempotency-Key replay (same body returns existing bookingId in details)",
  })
  async create(
    @Body(new ZodValidationPipe(createBookingSchema))
    createBookingDto: CreateBookingDto,
    @IdempotencyKey()
    idempotencyKey: string,
    @CurrentUser() currentUser: AuthenticatedUser,
  ): Promise<V2BookingResponseDto> {
    return this.bookingsService.create(
      createBookingDto,
      currentUser.id,
      idempotencyKey,
    ) as Promise<V2BookingResponseDto>;
  }

  @Patch(":id/status")
  @ApiOperation({
    summary: "Update booking status",
    description: `
       Updates the status of a booking using domain State transitions.

       **Allowed transitions:**
       - "pending" → "confirmed"
       - "pending" → "cancelled"
       - "confirmed" → "completed"
       - "confirmed" → "cancelled"
       - "completed" → "cancelled"
     `,
  })
  @ApiParam({
    name: "id",
    description: "Booking UUID",
    example: "123e4567-e89b-12d3-a456-426614174000",
    format: "uuid",
  })
  @ApiBody({ type: V2UpdateBooking })
  @ApiResponse({
    status: 200,
    description: "Booking status updated successfully",
    type: V2BookingResponse,
  })
  @ApiResponse({
    status: 400,
    description: "Invalid input data",
  })
  @ApiResponse({
    status: 401,
    description: "Unauthorized - Authentication required",
  })
  @ApiResponse({
    status: 403,
    description: "Forbidden - You can only update your own bookings unless you are an Admin",
  })
  @ApiResponse({
    status: 404,
    description: "Booking not found",
  })
  @ApiResponse({
    status: 409,
    description:
      "Illegal status transition, offer no longer active, or max concurrent bookings reached",
  })
  async updateStatus(
    @Param("id") bookingId: string,
    @Body(new ZodValidationPipe(v2UpdateBookingStatusSchema))
    updateStatusDto: V2UpdateBookingStatusDto,
    @CurrentUser() currentUser: AuthenticatedUser,
  ): Promise<V2BookingResponseDto> {
    return this.bookingsService.changeStatus(
      bookingId,
      updateStatusDto,
      currentUser.id,
      currentUser.role,
    ) as Promise<V2BookingResponseDto>;
  }
}
